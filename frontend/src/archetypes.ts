// Архетипы для карточки шеринга — своё название на каждую из 8 игр,
// 5 титулов на шкалу процентиля: 0-20 / 21-40 / 41-60 / 61-80 / 81-100.
// Порядок — от низкого выражения черты к высокому (после инверсии, где она есть,
// см. traits.ts: тот же invert-флаг определяет направление и здесь).
type Tiers = [string, string, string, string, string];

const ARCHETYPES: Record<string, Tiers> = {
  balloon: ["Сверхосторожный", "Осторожный игрок", "Взвешенный игрок", "Азартный игрок", "Игрок ва-банк"],
  loss: ["Хладнокровный трейдер", "Спокоен к потерям", "Обычная осторожность", "Бережёт своё", "Синица в руках"],
  patience: ["Хочу всё и сразу", "Нетерпеливый", "Умеренно терпеливый", "Терпеливый стратег", "Мастер выдержки"],
  decks: ["Наступает на грабли", "Учится не спеша", "Средний ученик", "Схватывает на лету", "Прирождённый стратег"],
  trust: ["Крепость на замке", "Осторожное доверие", "В меру доверчивый", "Открытая душа", "Доверяет всем подряд"],
  ultimatum: ["Берёт что дают", "Гибкая справедливость", "Умеренный принцип", "Борец за правду", "Непреклонный принцип"],
  beauty: ["Наивный оптимист", "Простая логика", "Пара шагов вперёд", "Стратегический ум", "На пять ходов вперёд"],
  reflection: ["Доверяет первому импульсу", "Иногда попадается", "В меру внимательный", "Проверяет дважды", "Ловец своих ошибок"],
};

function tierIndex(percentile: number): number {
  if (percentile <= 20) return 0;
  if (percentile <= 40) return 1;
  if (percentile <= 60) return 2;
  if (percentile <= 80) return 3;
  return 4;
}

/**
 * rawPercentile — процентиль сырой метрики, тот же `p`, что передаётся в
 * summarize().primary.comparison(p). invert — trait.invert из traits.ts:
 * для черт с обратной шкалой (например, Терпеливость) высокий титул
 * должен triggерить на НИЗКОМ сыром проценте.
 */
export function archetypeTitle(testId: string, rawPercentile: number, invert?: boolean): string | null {
  const tiers = ARCHETYPES[testId];
  if (!tiers) return null;
  const p = invert ? 100 - rawPercentile : rawPercentile;
  return tiers[tierIndex(p)];
}
