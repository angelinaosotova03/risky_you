export interface Trait {
  /** Человеческое название черты для оси диаграммы и плитки */
  label: string;
  /**
   * true, если у этого теста больший процентиль по primary-метрике означает
   * МЕНЬШЕ выраженности черты (например: чем точнее ответ — тем меньше отклонение,
   * но мы хотим показывать на оси именно точность, а не отклонение)
   */
  invert?: boolean;
  /**
   * Плausible-диапазон [min, max] значения primary-метрики этого теста.
   * Используется ТОЛЬКО как временная замена процентилю, пока других участников
   * мало для честного сравнения — чтобы твой собственный результат не пропадал
   * с диаграммы, а показывался хоть какой-то оценкой до появления реальных данных.
   */
  range?: [number, number];
}

